def test_qa_health_stale_artifact_is_not_presented_as_current(monkeypatch, tmp_path: Path) -> None:
    """A frozen snapshot must not be served as "Latest CI artifact".

    ``qa-health.yml`` rebuilds on every push to main, so a healthy artifact is
    hours old. Production shipped one baked into the image at build time and
    frozen for weeks, and the only freshness check on the file was a size cap —
    so the dashboard reported month-old suite results with full confidence.

    ``unavailable`` is the honest answer, and it is an existing status every
    consumer already handles.
    """
    stale = datetime.now(timezone.utc) - timedelta(days=30)
    artifact = tmp_path / "qa.json"
    artifact.write_text(
        json.dumps(_valid_summary(generated_at=stale.isoformat().replace("+00:00", "Z"))),
        encoding="utf-8",
    )
    monkeypatch.setenv("QA_HEALTH_SUMMARY_PATH", str(artifact))
    client = TestClient(_build_app(_make_user(is_sysadmin=True)))

    resp = client.get("/v1/system/qa-health")

    assert resp.status_code == 200
    body = resp.json()
    assert body["overall"]["status"] == "unavailable"
    # The stale numbers must not leak through alongside the honest status.
    assert body["suites"] == []
    assert "stale" in body["source"]["note"].lower()
    assert "30 days ago" in body["source"]["note"]


def test_qa_health_artifact_just_inside_the_window_is_served(monkeypatch, tmp_path: Path) -> None:
    """The guard must not fire on a merely quiet weekend."""
