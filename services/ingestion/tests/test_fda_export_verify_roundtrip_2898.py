"""Regression tests for #2898 — /export/verify must not report untampered exports as tampered.

``/export/verify`` exists to prove an export "hasn't been tampered with".
Two independent mechanisms made it emit ``MISMATCH_DETECTED`` — which reads
as evidence tampering — for a genuine, untampered export:

(a) ``include_pii`` materially changes the exported bytes (``_redact_location_value``
    substitutes ``[REDACTED]`` into five columns, ``_redact_extra_kde_pii``
    scrubs the Additional-KDEs blob), but it was never persisted in
    ``fsma.fda_export_log``. The verifier therefore always regenerated the
    *redacted* CSV, even for an export hashed over unredacted bytes.

(b) Since #2515 the exporter reconstructs ``/export/all``'s event set with one
    set-based ``query_events_by_tlcs`` call while the verifier re-derived it
    with a per-seed ``query_events_by_tlc`` fan-out — a different algorithm,
    and therefore a different row order and a different hash.

The fix records ``include_pii`` (and the ``event_type`` filter, the other
byte-determining input that was never stored) in the audit row, and routes
both the exporter and the verifier through one shared reconstruction helper.

Fail-closed rule (FSMA 204 audit evidence): an audit row that cannot fully
determine the regenerated bytes — e.g. a legacy row written before
``include_pii`` was captured — must return HTTP 409, never a tamper verdict.
"""

