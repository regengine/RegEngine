class _FakeSession:
    """Session whose single SELECT returns a scripted fda_export_log row."""

    def __init__(self, row: Optional[tuple] = None):
        self.row = row
        self.executes: list[Any] = []
        self.closed = False

    def execute(self, statement, params=None):
        self.executes.append((str(statement), params))
        outer = self

        class _R:
            def fetchone(self):
                return outer.row

            def fetchall(self):
                return []

        return _R()

    def commit(self) -> None:
        return None

    def rollback(self) -> None:
        return None

    def close(self) -> None:
        self.closed = True


def _event(idx: int, tlc: str) -> dict:
    """An event carrying PII in every redactable column, so include_pii
    demonstrably changes the CSV bytes."""
    return {
        "id": f"evt-{idx}",
        "event_type": "shipping",
        "traceability_lot_code": tlc,
        "product_description": "Romaine Hearts",
        "quantity": 1.0,
        "unit_of_measure": "cases",
        "location_gln": "0614141000005",
        "location_name": f"Valley Fresh Farms {idx}",
        "event_timestamp": f"2026-03-1{idx}T09:00:00+00:00",
        "sha256_hash": "a" * 64,
        "chain_hash": "b" * 64,
        "source": "webhook",
        "ingested_at": "2026-03-20T09:00:00+00:00",
        "kdes": {
            "ship_date": "2026-03-10",
            "ship_from_location": f"Valley Fresh Farms {idx}",
            "ship_to_location": "Metro DC",
            "facility_address": "1 Packing House Rd",
        },
    }


class _RecordingPersistence:
    """Fake CTEPersistence shared by the export leg and the verify leg.

    Both legs see the same underlying data, so any hash mismatch is the
    exporter and verifier disagreeing on the algorithm — not tampering.
    """

    log_export_calls: list[dict] = []
    per_tlc_calls: list[dict] = []
    batch_calls: list[dict] = []

    def __init__(self, _session=None):
        pass

    @classmethod
    def reset(cls) -> None:
        cls.log_export_calls = []
        cls.per_tlc_calls = []
        cls.batch_calls = []

    # Seed query: one event per lot code.
    def query_all_events(self, **kwargs):
        seeds = [{"id": f"evt-{i}", "traceability_lot_code": t} for i, t in enumerate(TLCS)]
        return (seeds, len(seeds))

    def query_events_by_tlc(self, **kwargs):
        type(self).per_tlc_calls.append(kwargs)
        return [_event(TLCS.index(kwargs["tlc"]), kwargs["tlc"])]

    def query_events_by_tlcs(self, tenant_id, tlcs, **kwargs):
        type(self).batch_calls.append({"tenant_id": tenant_id, "tlcs": list(tlcs), **kwargs})
        return [_event(i, t) for i, t in enumerate(tlcs)]

    def verify_chain(self, **_kwargs):
        return _FakeChainVerification()

    def log_export(self, **kwargs):
        type(self).log_export_calls.append(kwargs)
        return "export-log-id"


def _install_fakes(monkeypatch, session: _FakeSession) -> None:
    fake_db = types.ModuleType("shared.database")
    fake_db.SessionLocal = lambda: session
    monkeypatch.setitem(sys.modules, "shared.database", fake_db)
    monkeypatch.setattr(shared_cte_persistence, "CTEPersistence", _RecordingPersistence)


def _make_client(monkeypatch, session: _FakeSession) -> TestClient:
    app = FastAPI()
    app.include_router(fda_router)
    install_ingestion_principal_override(
        app,
        IngestionPrincipal(key_id="test-key", scopes=["*"], auth_mode="test"),
    )
    install_active_subscription_override(app)
    _install_fakes(monkeypatch, session)
    return TestClient(app)


def _audit_row(
    *,
    export_type: str = "fda_export_all",
    query_tlc: Optional[str] = None,
    record_count: int = len(TLCS),
    export_hash: str = "h",
    include_pii: Optional[bool] = False,
    query_event_type: Optional[str] = None,
) -> tuple:
    """The fda_export_log row shape ``verify_export_handler`` selects."""
    return (
        export_type,
        query_tlc,
        START,
        END,
        record_count,
        export_hash,
        None,  # generated_at
        include_pii,
        query_event_type,
    )


