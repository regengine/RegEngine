class TestExportVerifyRoundTrip:
    @pytest.mark.parametrize("include_pii", [True, False])
    def test_export_all_round_trip_verifies(self, monkeypatch, include_pii):
        _RecordingPersistence.reset()
        client = _make_client(monkeypatch, _FakeSession())
        with client:
            r = client.get(
                "/api/v1/fda/export/all",
                params={
                    "tenant_id": TENANT,
                    "start_date": START,
                    "end_date": END,
                    "allow_incomplete": "true",
                    "include_pii": str(include_pii).lower(),
                },
            )
        assert r.status_code == 200, r.text
        logged = _RecordingPersistence.log_export_calls[0]

        # Same tenant, same data, no tampering — verification must reproduce
        # the exporter's hash byte for byte.
        session = _FakeSession(
            _audit_row(
                export_type=logged["export_type"],
                record_count=logged["record_count"],
                export_hash=logged["export_hash"],
                include_pii=logged["include_pii"],
                query_event_type=logged["query_event_type"],
            )
        )
        _install_fakes(monkeypatch, session)
        out = asyncio.run(v.verify_export_handler("exp-full", TENANT))

        assert out["hashes_match"] is True
        assert out["data_integrity"] == "VERIFIED"
        assert out["current_record_count"] == logged["record_count"]

    def test_single_tlc_round_trip_with_pii_verifies(self, monkeypatch):
        _RecordingPersistence.reset()
        client = _make_client(monkeypatch, _FakeSession())
        with client:
            r = client.get(
                "/api/v1/fda/export",
                params={
                    "tenant_id": TENANT,
                    "tlc": TLCS[0],
                    "format": "csv",
                    "allow_incomplete": "true",
                    "include_pii": "true",
                },
            )
        assert r.status_code == 200, r.text
        logged = _RecordingPersistence.log_export_calls[0]

        session = _FakeSession(
            _audit_row(
                export_type=logged["export_type"],
                query_tlc=logged["query_tlc"],
                record_count=logged["record_count"],
                export_hash=logged["export_hash"],
                include_pii=logged["include_pii"],
            )
        )
        _install_fakes(monkeypatch, session)
        out = asyncio.run(v.verify_export_handler("exp-tlc", TENANT))

        assert out["hashes_match"] is True
        assert out["data_integrity"] == "VERIFIED"

    def test_tampered_export_still_reports_mismatch(self, monkeypatch):
        """The fix must not make the verifier laxer: a hash that genuinely
        does not reproduce is still MISMATCH_DETECTED."""
        _RecordingPersistence.reset()
        session = _FakeSession(_audit_row(export_hash="0" * 64))
        _install_fakes(monkeypatch, session)
        out = asyncio.run(v.verify_export_handler("exp-tampered", TENANT))
        assert out["hashes_match"] is False
        assert out["data_integrity"] == "MISMATCH_DETECTED"
