class TestSharedReconstruction:
    def test_full_export_verification_uses_the_batch_query(self, monkeypatch):
        """No per-seed ``query_events_by_tlc`` fan-out may remain in the
        full-export verification path — that loop is mechanism (b)."""
        _RecordingPersistence.reset()
        session = _FakeSession(_audit_row())
        _install_fakes(monkeypatch, session)
        monkeypatch.setattr(v, "_generate_csv", lambda events, *, include_pii=False: "csv")

        asyncio.run(v.verify_export_handler("exp-full", TENANT))

        assert _RecordingPersistence.per_tlc_calls == []
        assert len(_RecordingPersistence.batch_calls) == 1
        assert _RecordingPersistence.batch_calls[0]["tlcs"] == list(TLCS)

    def test_exporter_and_verifier_share_one_helper(self, monkeypatch):
        """Both legs must go through the same reconstruction function, so the
        two can never drift apart again."""
        from services.ingestion.app.fda_export import queries as q

        assert hasattr(q, "reconstruct_full_export_events")

        calls: list[dict] = []
        real = q.reconstruct_full_export_events

        def _spy(persistence, **kwargs):
            calls.append(kwargs)
            return real(persistence, **kwargs)

        import services.ingestion.app.fda_export.router as router_mod

        monkeypatch.setattr(router_mod, "reconstruct_full_export_events", _spy)
        monkeypatch.setattr(v, "reconstruct_full_export_events", _spy)

        _RecordingPersistence.reset()
        client = _make_client(monkeypatch, _FakeSession())
        with client:
            r = client.get(
                "/api/v1/fda/export/all",
                params={
                    "tenant_id": TENANT,
                    "start_date": START,
                    "end_date": END,
                    "allow_incomplete": "true",
                },
            )
        assert r.status_code == 200, r.text

        session = _FakeSession(_audit_row())
        _install_fakes(monkeypatch, session)
        monkeypatch.setattr(v, "_generate_csv", lambda events, *, include_pii=False: "csv")
        asyncio.run(v.verify_export_handler("exp-full", TENANT))

        assert len(calls) == 2, "exporter and verifier must both use the shared helper"
        assert calls[0] == calls[1], "same tenant/window/filters must reconstruct identically"


