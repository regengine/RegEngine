class TestVerifierHonoursRecordedPii:
    @pytest.mark.parametrize("include_pii", [True, False])
    def test_generate_csv_receives_the_recorded_flag(self, monkeypatch, include_pii):
        _RecordingPersistence.reset()
        session = _FakeSession(_audit_row(export_type="fda_spreadsheet", query_tlc=TLCS[0], include_pii=include_pii))
        _install_fakes(monkeypatch, session)

        seen: list[bool] = []

        def _fake_csv(events, *, include_pii=False):
            seen.append(include_pii)
            return "csv"

        monkeypatch.setattr(v, "_generate_csv", _fake_csv)
        asyncio.run(v.verify_export_handler("exp-1", TENANT))
        assert seen == [include_pii]

    def test_unrecorded_pii_flag_fails_closed_with_409(self, monkeypatch):
        """A legacy audit row (include_pii NULL) cannot determine the bytes.

        It must 409, never be reported as tampered.
        """
        _RecordingPersistence.reset()
        session = _FakeSession(_audit_row(export_type="fda_spreadsheet", query_tlc=TLCS[0], include_pii=None))
        _install_fakes(monkeypatch, session)

        with pytest.raises(HTTPException) as exc_info:
            asyncio.run(v.verify_export_handler("exp-legacy", TENANT))
        assert exc_info.value.status_code == 409
        assert "MISMATCH" not in str(exc_info.value.detail).upper()
        assert session.closed is True


