class TestIncludePiiIsRecorded:
    @pytest.mark.parametrize("include_pii", [True, False])
    def test_export_all_records_the_pii_flag(self, monkeypatch, include_pii):
        _RecordingPersistence.reset()
        client = _make_client(monkeypatch, _FakeSession())
        with client:
            r = client.get(
                "/api/v1/fda/export/all",
                params={
                    "tenant_id": TENANT,
                    "start_date": START,
                    "end_date": END,
                    "allow_incomplete": "true",
                    "include_pii": str(include_pii).lower(),
                },
            )
        assert r.status_code == 200, r.text
        assert _RecordingPersistence.log_export_calls[0]["include_pii"] is include_pii

    def test_single_tlc_export_records_the_pii_flag(self, monkeypatch):
        _RecordingPersistence.reset()
        client = _make_client(monkeypatch, _FakeSession())
        with client:
            r = client.get(
                "/api/v1/fda/export",
                params={
                    "tenant_id": TENANT,
                    "tlc": "TLC-0001",
                    "format": "csv",
                    "allow_incomplete": "true",
                    "include_pii": "true",
                },
            )
        assert r.status_code == 200, r.text
        assert _RecordingPersistence.log_export_calls[0]["include_pii"] is True

    def test_export_all_records_the_event_type_filter(self, monkeypatch):
        """``event_type`` narrows the seed set and therefore the exported
        bytes; the audit row must carry it or the export is unreproducible."""
        _RecordingPersistence.reset()
        client = _make_client(monkeypatch, _FakeSession())
        with client:
            r = client.get(
                "/api/v1/fda/export/all",
                params={
                    "tenant_id": TENANT,
                    "start_date": START,
                    "end_date": END,
                    "allow_incomplete": "true",
                    "event_type": "shipping",
                },
            )
        assert r.status_code == 200, r.text
        assert _RecordingPersistence.log_export_calls[0]["query_event_type"] == "shipping"

    def test_log_export_writes_the_columns(self):
        """The persistence layer must actually put the flag in the INSERT."""
        from shared.cte_persistence import CTEPersistence

        recorded: list[tuple[str, dict]] = []

        class _Sess:
            def execute(self, statement, params=None):
                recorded.append((str(statement), params or {}))

                class _R:
                    def fetchone(self_inner):
                        return ("11111111-1111-1111-1111-111111111111",)

                return _R()

        CTEPersistence(_Sess()).log_export(
            tenant_id=TENANT,
            export_hash="a" * 64,
            record_count=1,
            include_pii=True,
            query_event_type="shipping",
        )
        stmt, params = recorded[0]
        assert "include_pii" in stmt
        assert "query_event_type" in stmt
        assert params["pii"] is True
        assert params["qetype"] == "shipping"


