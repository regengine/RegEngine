import React from 'react';
import { act, cleanup, renderHook, waitFor } from '@testing-library/react';
import { useQueryClient } from '@tanstack/react-query';
import { afterEach, expect, it, vi } from 'vitest';
import { Providers } from '@/lib/providers';
import { useAuth } from '@/lib/auth-context';
import { useTenant } from '@/lib/tenant-context';
vi.mock('next-themes', () => ({ThemeProvider:({children}:React.PropsWithChildren) => <>{children}</>}));
vi.mock('@/lib/posthog-provider', () => ({CSPostHogProvider:({children}:React.PropsWithChildren) => <>{children}</>}));
vi.mock('@/components/ui/toaster', () => ({Toaster: () => null}));
vi.mock('@/lib/api-client', () => ({apiClient:{setAccessToken:vi.fn(),setUser:vi.fn(),setCurrentTenant:vi.fn()}}));
afterEach(() => {cleanup();localStorage.clear();vi.unstubAllGlobals();});
it('actual provider tenant A to B switch cancels deferred A and clears cache', async () => {
 vi.stubGlobal('fetch',vi.fn().mockResolvedValue({ok:true,json:async () => ({authenticated:true,tenant_id:'tenant-a',user:{id:'a',email:'a@example.test'},auth_method:'webauthn'})}));
 const wrapper = ({children}:React.PropsWithChildren) => <Providers>{children}</Providers>;
 const hook = renderHook(() => ({auth:useAuth(),tenant:useTenant(),cache:useQueryClient()}),{wrapper});
 await waitFor(() => expect(hook.result.current.tenant.tenantId).toBe('tenant-a'));
 let resolve!: (value: string) => void;
 const pending = new Promise<string>(r => {resolve=r;});
 const oldRequest = hook.result.current.cache.fetchQuery({queryKey:['sensitive'],queryFn:() => pending}).catch(() => undefined);
 hook.result.current.cache.setQueryData(['previous'], 'account-a');
 act(() => hook.result.current.tenant.setTenantId('tenant-b'));
 await act(async () => {resolve('account-a');await oldRequest;});
 expect(hook.result.current.tenant.tenantId).toBe('tenant-b');
 expect(hook.result.current.cache.getQueryData(['sensitive'])).toBeUndefined();
 expect(hook.result.current.cache.getQueryData(['previous'])).toBeUndefined();
});
it('successful API-key replacement cancels old credential results and clears prior data', async () => {
 vi.stubGlobal('fetch',vi.fn().mockResolvedValue({ok:true,json:async () => ({authenticated:true,tenant_id:'tenant-a',user:{id:'a',email:'a@example.test'},has_api_key:true})}));
 const wrapper = ({children}:React.PropsWithChildren) => <Providers>{children}</Providers>;
 const hook = renderHook(() => ({auth:useAuth(),cache:useQueryClient()}),{wrapper});
 await waitFor(() => expect(hook.result.current.auth.isHydrated).toBe(true));
 let resolve!: (value:string) => void;
 const pending = new Promise<string>(r => {resolve=r;});
 const oldRequest = hook.result.current.cache.fetchQuery({queryKey:['credential-sensitive'],queryFn:() => pending}).catch(() => undefined);
 hook.result.current.cache.setQueryData(['old-key'], 'old-data');
 await act(async () => {await hook.result.current.auth.setApiKey('synthetic-new-key');resolve('old-data');await oldRequest;});
 expect(hook.result.current.cache.getQueryData(['credential-sensitive'])).toBeUndefined();
 expect(hook.result.current.cache.getQueryData(['old-key'])).toBeUndefined();
});
it('failed API-key replacement preserves the current credential cache/version', async () => {
 vi.stubGlobal('fetch',vi.fn(async (_url, options) => options?.method === 'POST' ? {ok:false,status:503} : {ok:true,json:async () => ({authenticated:false,has_api_key:true,tenant_id:'tenant-a'})}));
 const wrapper = ({children}:React.PropsWithChildren) => <Providers>{children}</Providers>;
 const hook = renderHook(() => ({auth:useAuth(),cache:useQueryClient()}),{wrapper});
 await waitFor(() => expect(hook.result.current.auth.isHydrated).toBe(true));
 const version = hook.result.current.auth.sessionIdentityVersion;
 hook.result.current.cache.setQueryData(['old-key'], 'old-data');
 await act(async () => {await expect(hook.result.current.auth.setApiKey('synthetic-rejected-key')).rejects.toThrow(/could not be saved/);});
 expect(hook.result.current.cache.getQueryData(['old-key'])).toBe('old-data');
 expect(hook.result.current.auth.sessionIdentityVersion).toBe(version);
});
it('removing local API-key context also clears cached sensitive data', async () => {
 vi.stubGlobal('fetch',vi.fn().mockResolvedValue({ok:true,json:async () => ({authenticated:false,has_api_key:true,tenant_id:'tenant-a'})}));
 const wrapper = ({children}:React.PropsWithChildren) => <Providers>{children}</Providers>;
 const hook = renderHook(() => ({auth:useAuth(),cache:useQueryClient()}),{wrapper});
 await waitFor(() => expect(hook.result.current.auth.isHydrated).toBe(true));
 hook.result.current.cache.setQueryData(['old-key'], 'old-data');
 await act(async () => {await hook.result.current.auth.setApiKey(null);});
 expect(hook.result.current.auth.apiKey).toBeNull();
 expect(hook.result.current.cache.getQueryData(['old-key'])).toBeUndefined();
});
