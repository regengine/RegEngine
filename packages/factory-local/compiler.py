"""Compile a DeonticIR into a Rego v1 policy with strict compliance_status precedence.

compliance_status precedence, highest first, each body excluding the ones above it:
  COMPLIANT                  applicable and action satisfied
  COMPLIANT_VIA_SAFE_HARBOR  applicable, action not satisfied, safe harbor true
  NON_COMPLIANT_BREACH       applicable, action not satisfied, no safe harbor
  EXEMPT_OR_NOT_APPLICABLE   default

Controls are tested as `input.controls.X == true` / `not input.controls.X == true`
so a missing key behaves exactly like false. verify.py mirrors these bodies.
"""

from __future__ import annotations

import json

from schemas import DeonticIR, DeonticPredicate, Modality, Operator, is_safe_identifier, is_safe_path

_OPS = {Operator.GREATER_THAN: ">", Operator.LESS_THAN: "<", Operator.EQUALS: "=="}


def _literal(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    if isinstance(value, (int, float)):
        return repr(value)
    return json.dumps(value)  # JSON string literals are valid Rego strings


def _predicate(p: DeonticPredicate) -> str:
    if not is_safe_path(p.fact):
        raise ValueError(f"unsafe fact path: {p.fact!r}")
    return f"input.{p.fact} {_OPS[p.operator]} {_literal(p.value)}"


def _control(name: str, satisfied: bool) -> str:
    if not is_safe_identifier(name):
        raise ValueError(f"unsafe control name: {name!r}")
    test = f"input.controls.{name} == true"
    return test if satisfied else f"not {test}"


def action_test(ir: DeonticIR, satisfied: bool) -> str:
    """Rego line for 'action satisfied' (or its negation).

    OBLIGATION: satisfied when the control is true.
    PROHIBITION: satisfied when the control is not true (the act did not occur).
    """
    want_true = satisfied if ir.modality == Modality.OBLIGATION else not satisfied
    return _control(ir.action_required, want_true)


def compile_ir_to_rego(ir: DeonticIR, pkg: str) -> str:
    if not is_safe_path(pkg):
        raise ValueError(f"unsafe package name: {pkg!r}")
    applicable = [_predicate(p) for p in ir.applicability_predicates] or ["true"]
    penalty = _literal(ir.max_penalty_usd)
    safe_harbor = _control(ir.safe_harbor_control, True) if ir.safe_harbor_control else "false"
    no_safe_harbor = _control(ir.safe_harbor_control, False) if ir.safe_harbor_control else "true"

    def body(*lines: str) -> str:
        return "\n".join(f"\t{line}" for line in lines)

    return f"""package {pkg}

import rego.v1

# Generated by factory-local from DeonticIR {ir.rule_id}. Do not edit by hand.
# Citation: {json.dumps(ir.citation)}

default compliance_status := "EXEMPT_OR_NOT_APPLICABLE"

default violation_exposure_usd := 0

rule_id := {json.dumps(ir.rule_id)}

citation := {json.dumps(ir.citation, ensure_ascii=False)}

is_applicable if {{
{body(*applicable)}
}}

compliance_status := "COMPLIANT" if {{
{body("is_applicable", action_test(ir, True))}
}}

compliance_status := "COMPLIANT_VIA_SAFE_HARBOR" if {{
{body("is_applicable", action_test(ir, False), safe_harbor)}
}}

compliance_status := "NON_COMPLIANT_BREACH" if {{
{body("is_applicable", action_test(ir, False), no_safe_harbor)}
}}

violation_exposure_usd := input.affected_consumer_count * {penalty} if {{
\tcompliance_status == "NON_COMPLIANT_BREACH"
}}

result := {{
\t"rule_id": rule_id,
\t"citation": citation,
\t"compliance_status": compliance_status,
\t"violation_exposure_usd": violation_exposure_usd,
}}
"""
