#!/usr/bin/env python3
"""Regenerate public sample exports from the synthetic CTE source CSVs.

This script is the source of truth for the artifacts under ``demo_exports/``
that get promoted to RegEngine's public Proof Surface. It must be:

* **Deterministic** — same inputs in ``sample_data/`` always produce
  identical bytes in ``demo_exports/``. CI uses ``git diff --exit-code``
  on the output to catch silent drift between the public sample and
  current production behavior.
* **Idempotent** — re-running with no input changes is a no-op.
* **Pure-Python** — no live database, no network, no test fixtures.
  All inputs are the synthetic CSVs already on disk.

The three artifacts produced are:

1. ``sample_fda_export.csv`` — FDA 21 CFR 1.1455 sortable spreadsheet
   generated by the production
   :func:`services.ingestion.app.fda_export_service._generate_csv`
   helper. This is the same code path the ``/api/v1/export/fda`` route
   uses to serialize CTE events.
2. ``sample_epcis.json`` — GS1 EPCIS 2.0 JSON-LD bundle, built using the
   production CTE-to-bizStep mapping in
   :mod:`services.ingestion.app.epcis_export`.
3. ``sample_audit_bundle.json`` — Per-event SHA-256 record hashes, the
   chain hash sequence, and a Merkle root computed by
   :func:`services.shared.merkle_tree.compute_merkle_root`.

Production-code parity matters: if FDA columns change or the EPCIS
bizStep map changes, the regenerator picks the new behavior up
automatically and the CI diff trips, forcing the public sample to be
re-committed in the same PR. That keeps the Proof Surface honest.

If the script cannot import the production helpers (e.g. CI environment
without service deps installed), it exits 0 with a warning rather than
failing. The audit + ``SYNTHETIC.md`` notes are the must-have part; the
end-to-end regeneration is best-effort.
"""

from __future__ import annotations

import csv
import hashlib
import json
import logging
import sys
from datetime import datetime, timezone
from pathlib import Path

logger = logging.getLogger("regenerate_public_samples")
logging.basicConfig(level=logging.INFO, format="%(message)s")

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
REPO_ROOT = Path(__file__).resolve().parent.parent
SAMPLE_DIR = REPO_ROOT / "sample_data"
EXPORT_DIR = REPO_ROOT / "demo_exports"

# Fixed-seed test tenant id (UUID5 over a stable name) so the script is
# reproducible. Not a real tenant in any environment.
DEMO_TENANT_ID = "00000000-0000-4000-8000-0000000000d1"

# Frozen "generated_at" timestamp baked into the artifacts. Using a
# fixed value keeps the output bytes identical across runs — required
# for the CI ``git diff --exit-code`` drift check.
FROZEN_TIMESTAMP = "2026-01-01T00:00:00+00:00"


# ---------------------------------------------------------------------------
# Production-code import shim
# ---------------------------------------------------------------------------
def _try_import_production_helpers():
    """Try to import the FDA / EPCIS / Merkle helpers from the services tree.

    Returns ``(generate_csv, cte_to_bizstep, compute_merkle_root)`` on
    success, or ``None`` if any import fails. Mirrors the sys.path setup
    in ``services/ingestion/conftest.py`` so the relative imports inside
    ``app/`` resolve.
    """
    services_ingestion = REPO_ROOT / "services" / "ingestion"
    services_dir = REPO_ROOT / "services"
    for p in (services_ingestion, services_dir, REPO_ROOT):
        sp = str(p)
        if sp not in sys.path:
            sys.path.insert(0, sp)

    try:
        # Import order matters: fda_export_service pulls in
        # ``shared.fda_export`` and ``app.shared.csv_safety`` which both
        # need to be on sys.path before this line.
        from app.epcis_export import _CTE_TO_BIZSTEP  # type: ignore
        from app.fda_export_service import _generate_csv  # type: ignore
        from shared.merkle_tree import compute_merkle_root  # type: ignore
    except Exception as exc:  # noqa: BLE001 — best-effort import
        logger.warning(
            "regenerate_public_samples: production helpers unavailable (%s); "
            "skipping regeneration. The audit + SYNTHETIC.md notes are the "
            "must-have part. TODO: requires test fixture tenant",
            exc,
        )
        return None

    return _generate_csv, _CTE_TO_BIZSTEP, compute_merkle_root


# ---------------------------------------------------------------------------
# Source CSV → CTE event dict
# ---------------------------------------------------------------------------
# Map each source CSV filename to the CTE event_type and the KDE column
# names it carries. Mirrors the production WebhookCTEType taxonomy.
_SOURCE_FILES = [
    ("01_harvesting.csv", "harvesting"),
    ("02_cooling.csv", "cooling"),
    ("03_initial_packing.csv", "initial_packing"),
    ("04_shipping.csv", "shipping"),
    ("05_receiving.csv", "receiving"),
    ("06_transformation.csv", "transformation"),
]

# Columns that always belong on the top-level event dict (not in kdes).
_TOP_LEVEL_COLUMNS = {
    "traceability_lot_code",
    "product_description",
    "quantity",
    "unit_of_measure",
    "location_name",
    "location_gln",
}

# Synthetic deterministic clock for event_timestamp values. Using a
# function of (event_type, source_row_idx) keeps the timestamp tied to
# input position so reordering rows changes hashes (which is the
# correct production behavior).
_BASE_HOUR_BY_CTE = {
    "harvesting": 6,
    "cooling": 9,
    "initial_packing": 12,
    "shipping": 15,
    "receiving": 18,
    "transformation": 21,
}


def _row_to_event(event_type: str, row: dict, idx: int) -> dict:
    """Convert a CSV row into the event dict shape the FDA exporter expects."""
    # Pull a primary date column to anchor the timestamp on.
    date_col = next(
        (
            row.get(col)
            for col in (
                "harvest_date",
                "cooling_date",
                "packing_date",
                "ship_date",
                "receive_date",
                "transformation_date",
            )
            if row.get(col)
        ),
        "2026-01-01",
    )
    hour = _BASE_HOUR_BY_CTE.get(event_type, 12)
    minute = (idx * 7) % 60
    timestamp = f"{date_col}T{hour:02d}:{minute:02d}:00+00:00"

    kdes: dict[str, str] = {}
    top: dict[str, str] = {}
    for key, value in row.items():
        if not key:
            continue
        if key in _TOP_LEVEL_COLUMNS:
            top[key] = value or ""
        else:
            kdes[key] = value or ""

    # Map a few CSV-side names to the canonical KDE keys the exporter
    # consumes (mirrors the webhook normalization in production).
    if "carrier_name" in kdes and "carrier" not in kdes:
        kdes["carrier"] = kdes["carrier_name"]
    if "receiving_gln" in kdes and "ship_to_gln" not in kdes:
        kdes["ship_to_gln"] = kdes["receiving_gln"]

    event = {
        "event_type": event_type,
        "event_timestamp": timestamp,
        "source": "sample_data/" + event_type,
        "kdes": kdes,
        **top,
    }

    # Compute deterministic per-event SHA-256 hash over a canonical
    # JSON form. This matches the spirit of the production hashing
    # (cte_persistence does the same thing) without requiring a DB row.
    canonical = json.dumps(event, sort_keys=True, separators=(",", ":"))
    event["sha256_hash"] = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    return event


def _load_events() -> list[dict]:
    """Load all synthetic CTE rows from sample_data/ into event dicts."""
    events: list[dict] = []
    for filename, event_type in _SOURCE_FILES:
        path = SAMPLE_DIR / filename
        if not path.exists():
            logger.warning("regenerate_public_samples: missing %s, skipping", path)
            continue
        with path.open(newline="", encoding="utf-8") as fh:
            reader = csv.DictReader(fh)
            for idx, row in enumerate(reader):
                events.append(_row_to_event(event_type, row, idx))

    # Compute chain hashes deterministically: chain[0] = sha(prev=0,
    # record_hash); chain[i] = sha(chain[i-1], record_hash). Same shape
    # the production cte_persistence hash chain produces.
    prev = "0" * 64
    for event in events:
        chain_input = f"{prev}|{event['sha256_hash']}".encode("utf-8")
        event["chain_hash"] = hashlib.sha256(chain_input).hexdigest()
        prev = event["chain_hash"]
    return events


# ---------------------------------------------------------------------------
# Output writers
# ---------------------------------------------------------------------------
def _write_fda_csv(events: list[dict], generate_csv) -> Path:
    csv_content = generate_csv(events, include_pii=True)
    # Production helper uses csv module default CRLF line terminators.
    # Normalize to LF so the on-disk artifact matches git's stored
    # eol=lf and the CI ``git diff --exit-code`` drift check is stable
    # across platforms.
    csv_content = csv_content.replace("\r\n", "\n")
    out = EXPORT_DIR / "sample_fda_export.csv"
    out.write_bytes(csv_content.encode("utf-8"))
    logger.info("regenerate_public_samples: wrote %s (%d rows)", out, len(events))
    return out


def _write_epcis(events: list[dict], cte_to_bizstep: dict) -> Path:
    event_list = []
    for event in events:
        bizstep = cte_to_bizstep.get(event["event_type"], "urn:epcglobal:cbv:bizstep:observing")
        tlc = event.get("traceability_lot_code") or "UNKNOWN"
        gln = event.get("location_gln") or "0000000000000"
        event_list.append(
            {
                "type": "ObjectEvent",
                "eventTime": event["event_timestamp"],
                "eventTimeZoneOffset": "+00:00",
                "action": "OBSERVE",
                "bizStep": bizstep,
                "readPoint": {"id": f"urn:epc:id:sgln:{gln}.0"},
                "extension": {
                    "quantityList": [
                        {
                            "epcClass": f"urn:epc:class:lgtin:0000000.000000.{tlc}",
                            "quantity": event.get("quantity") or 0,
                            "uom": event.get("unit_of_measure") or "EA",
                        }
                    ]
                },
                "regengine:sha256": event["sha256_hash"],
                "regengine:chainHash": event["chain_hash"],
            }
        )

    doc = {
        "@context": [
            "https://ref.gs1.org/standards/epcis/2.0.0/epcis-context.jsonld",
            {"regengine": "https://regengine.co/ns/"},
        ],
        "id": f"urn:uuid:regengine-sample-{DEMO_TENANT_ID}",
        "type": "EPCISDocument",
        "schemaVersion": "2.0",
        "creationDate": FROZEN_TIMESTAMP,
        "epcisBody": {"eventList": event_list},
        "regengine:exportMetadata": {
            "tenantId": DEMO_TENANT_ID,
            "exportFormat": "EPCIS_2.0_JSON-LD",
            "generatedAt": FROZEN_TIMESTAMP,
            "eventsCount": len(event_list),
            "dataSource": "synthetic_sample",
            "syntheticDisclaimer": (
                "This document is generated from synthetic CTE data in sample_data/. See demo_exports/SYNTHETIC.md."
            ),
        },
    }

    out = EXPORT_DIR / "sample_epcis.json"
    out.write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    logger.info("regenerate_public_samples: wrote %s (%d events)", out, len(event_list))
    return out


def _write_audit_bundle(events: list[dict], compute_merkle_root) -> Path:
    record_hashes = [e["sha256_hash"] for e in events]
    merkle_root = compute_merkle_root(record_hashes) if record_hashes else None

    bundle = {
        "tenantId": DEMO_TENANT_ID,
        "generatedAt": FROZEN_TIMESTAMP,
        "dataSource": "synthetic_sample",
        "eventCount": len(events),
        "merkleRoot": merkle_root,
        "chainTip": events[-1]["chain_hash"] if events else None,
        "events": [
            {
                "index": idx,
                "eventType": e["event_type"],
                "traceabilityLotCode": e.get("traceability_lot_code", ""),
                "eventTimestamp": e["event_timestamp"],
                "recordHash": e["sha256_hash"],
                "chainHash": e["chain_hash"],
            }
            for idx, e in enumerate(events)
        ],
        "syntheticDisclaimer": (
            "Audit bundle generated from synthetic CTE data in sample_data/. See demo_exports/SYNTHETIC.md."
        ),
    }

    out = EXPORT_DIR / "sample_audit_bundle.json"
    out.write_text(json.dumps(bundle, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    logger.info(
        "regenerate_public_samples: wrote %s (root=%s)",
        out,
        (merkle_root or "")[:16],
    )
    return out


def main() -> int:
    EXPORT_DIR.mkdir(parents=True, exist_ok=True)

    helpers = _try_import_production_helpers()
    if helpers is None:
        # Best-effort: emit only the SYNTHETIC.md guard, leave previously
        # checked-in artifacts untouched. CI's diff check will still
        # pass because we didn't write anything.
        logger.warning(
            "regenerate_public_samples: production helpers not importable; exiting 0 without rewriting demo_exports/."
        )
        return 0

    generate_csv, cte_to_bizstep, compute_merkle_root = helpers

    events = _load_events()
    if not events:
        logger.error("regenerate_public_samples: no source rows found in %s", SAMPLE_DIR)
        return 1

    _write_fda_csv(events, generate_csv)
    _write_epcis(events, cte_to_bizstep)
    _write_audit_bundle(events, compute_merkle_root)
    return 0


if __name__ == "__main__":
    sys.exit(main())
